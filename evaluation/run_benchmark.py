"""Capture the current app's answers without changing its implementation or data.

Run from the project root: python3 evaluation/run_benchmark.py --repeat 3
The saved baseline is an actual fresh-context subagent response, not generated by
this script. Re-running this script re-evaluates only the local application.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import statistics
import sys
import time
from datetime import datetime, timezone
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from nitt_rag.engine import NITTAssistant


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--repeat", type=int, default=3)
    parser.add_argument("--output", type=Path, default=ROOT / "evaluation/app_results.json")
    args = parser.parse_args()
    if args.repeat < 1:
        parser.error("--repeat must be positive")
    questions = json.loads((ROOT / "evaluation/questions.json").read_text())
    hashes = {str(p.relative_to(ROOT)): digest(p) for p in sorted((ROOT / "nitt_rag").glob("*.py"))}
    hashes.update({str(p.relative_to(ROOT)): digest(p) for p in sorted((ROOT / "data").glob("*.json*"))})
    records = []
    blocked = RuntimeError("Network disabled for the offline evaluation")
    with patch("socket.create_connection", side_effect=blocked), patch("socket.socket.connect", side_effect=blocked):
        start = time.perf_counter()
        assistant = NITTAssistant()
        initialization_ms = (time.perf_counter() - start) * 1000
        for question in questions:
            samples, variants = [], []
            for _ in range(args.repeat):
                start = time.perf_counter()
                answer = assistant.ask(question["question"], top_k=6)
                samples.append((time.perf_counter() - start) * 1000)
                variants.append(answer.answer)
            record = {
                **question, "answer": answer.answer,
                "category": answer.category,
                "category_confidence": answer.category_confidence,
                "sources": answer.sources,
                "retrieved_course_codes": [r.chunk.metadata.get("course_code") for r in answer.results],
                "retrieved_sessions": [r.chunk.metadata.get("session") for r in answer.results],
                "latency_ms": samples,
                "median_latency_ms": statistics.median(samples),
                "same_answer_all_repeats": len(set(variants)) == 1,
            }
            records.append(record)
            print(question["id"], answer.category, f"{statistics.median(samples):.1f} ms", flush=True)
    payload = {
        "run_at_utc": datetime.now(timezone.utc).isoformat(),
        "protocol": "Frozen application; same 12 questions; top_k=6; repeated with one loaded index.",
        "network_check": "Python socket.connect and socket.create_connection blocked throughout initialization and queries.",
        "repeats": args.repeat,
        "initialization_ms": initialization_ms,
        "indexed_chunks": len(assistant.chunks),
        "source_sha256": hashes,
        "responses": records,
    }
    args.output.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n")
    print(f"Saved {args.output}")


if __name__ == "__main__":
    main()
